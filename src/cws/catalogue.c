int ProjectCWSDescriptor(int id, CWSDescriptor *d) {
  int uses[10] = {0}, slot, p, coordinate, shared, position;
  if (!d || id < 2 || id > 47)
    return 0;
  memset(d, 0, sizeof(*d));
  d->dimension = 5;
  for (slot = 0; slot < 5 && supports[id - 2][slot][0]; slot++) {
    d->row_count++;
    for (p = 0; p < 5 && supports[id - 2][slot][p]; p++) {
      coordinate = supports[id - 2][slot][p];
      uses[coordinate - 1]++;
      if (coordinate > d->coordinate_count)
        d->coordinate_count = coordinate;
    }
  }
  for (slot = 0; slot < d->row_count; slot++) {
    position = 0;
    for (shared = 1; shared >= 0; shared--)
      for (p = 0; p < 5 && supports[id - 2][slot][p]; p++) {
        coordinate = supports[id - 2][slot][p];
        if ((uses[coordinate - 1] > 1) == shared) {
          d->mappings[slot][position++] = coordinate;
          d->shared_counts[slot] += shared;
        }
      }
    d->row_sizes[slot] = position;
  }
  return 1;
}
