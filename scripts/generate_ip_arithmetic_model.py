#!/usr/bin/env python3
"""Source-link checked-IP arithmetic guards and return bodies to Lean models.

This restricted frontend is a trusted source-linking component, not a general
C++ parser. It rejects all unrecognized syntax and side effects.
"""
import argparse
import ast
import hashlib
from pathlib import Path
import re
from test_gpu_ip_source import block

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/gpu/ip_check.cuh'
OUTPUT = ROOT / 'proofs/Refpoly/CudaIPArithmeticSource.lean'


def translate(node):
    if isinstance(node, ast.Name) and node.id in ('a','b'):
        return node.id
    if isinstance(node, ast.Name) and node.id == 'failed':
        return 'True'
    if isinstance(node, ast.Constant) and type(node.value) is int:
        return str(node.value)
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        return f'(-{translate(node.operand)})'
    if isinstance(node, ast.BoolOp):
        op = ' ∧ ' if isinstance(node.op, ast.And) else ' ∨ '
        return '(' + op.join(translate(x) for x in node.values) + ')'
    if isinstance(node, ast.Compare) and len(node.ops) == 1:
        ops = {ast.Lt:'<',ast.LtE:'≤',ast.Gt:'>',ast.GtE:'≥',ast.Eq:'=',ast.NotEq:'≠'}
        return f'({translate(node.left)} {ops[type(node.ops[0])]} {translate(node.comparators[0])})'
    if isinstance(node, ast.BinOp):
        a,b = translate(node.left),translate(node.right)
        if isinstance(node.op,ast.Div):
            return f'(Int.tdiv ({a}) ({b}))'
        ops = {ast.Add:'+',ast.Sub:'-',ast.Mult:'*'}
        if type(node.op) in ops:
            return f'({a} {ops[type(node.op)]} {b})'
    raise ValueError(f'Unsupported guard syntax: {ast.dump(node)}')


def conditions(function):
    body = function[function.index('{')+1:function.rindex('}')]
    found = []
    for match in re.finditer(r'\bif\s*\(',body):
        begin = match.end()
        depth = 1
        end = begin
        while depth:
            if body[end] == '(':
                depth += 1
            elif body[end] == ')':
                depth -= 1
            end += 1
        condition = body[begin:end-1]
        expression = re.sub(r'([0-9]+)LL\b',r'\1',condition)
        expression = expression.replace('&&',' and ').replace('||',' or ')
        expression = ' '.join(expression.split())
        found.append((translate(ast.parse(expression,mode='eval').body), match.start(), end))
    return body,found


def generated():
    source = SOURCE.read_text()
    out = ['-- Generated by scripts/generate_ip_arithmetic_model.py; do not edit.',
           'import Refpoly.CudaIPArithmetic','', 'namespace Refpoly.CudaIP','']
    operators = {'add':'+','sub':'-','mul':'*','div':'/','rem':'%'}
    for name,operator in operators.items():
        function = block(source,'__device__ __forceinline__ long long device_ip_'+name+'(')
        header = re.sub(r'\s+','',function[:function.index('{')])
        expected_header = '__device____forceinline__longlongdevice_ip_'+name+'(longlonga,longlongb,int*failed)'
        if header != expected_header: raise ValueError(f'Unexpected typed signature for device_ip_{name}')
        body,guards = conditions(function)
        # The only admitted side effect is setting the sticky failure flag.
        guard,start,end = guards[-1]
        tail = re.sub(r'\s+','',body[end:])
        expected = '{atomicExch(failed,1);return0;}returna'+operator+'b;'
        if tail != expected:
            raise ValueError(f'Unexpected return/status body in device_ip_{name}')
        prefix = re.sub(r'//[^\n]*|\s+','',body[:start])
        if name == 'mul':
            expected_prefix = 'if(failed&&a>=-2147483648LL&&a<=2147483647LL&&b>=-2147483648LL&&b<=2147483647LL)returna*b;'
            if prefix != expected_prefix or len(guards) != 2:
                raise ValueError('Unexpected small-multiply fast path')
            out += [f'def sourceSmallMul (a b : Int) : Prop := {guards[0][0]}','']
        elif prefix or len(guards) != 1:
            raise ValueError(f'Unexpected statements before the guard in device_ip_{name}')
        cap = name.capitalize()
        out += [f'-- Function SHA256: {hashlib.sha256(function.encode()).hexdigest()}',
                f'def source{cap}Guard (a b : Int) : Prop := {guard}', '']
    out += ['''theorem source_add_guard_correct (a b : Int) (ha : fits64 a) (hb : fits64 b) :
    ¬ sourceAddGuard a b ↔ fits64 (a+b) := by
  have h : sourceAddGuard a b ↔ addOverflow a b := by
    norm_num [sourceAddGuard, addOverflow, min64, max64]
  rw [h]
  exact addOverflow_exact a b ha hb

theorem source_sub_guard_correct (a b : Int) (ha : fits64 a) (hb : fits64 b) :
    ¬ sourceSubGuard a b ↔ fits64 (a-b) := by
  have h : sourceSubGuard a b ↔ subOverflow a b := by
    norm_num [sourceSubGuard, subOverflow, min64, max64]
  rw [h]
  exact subOverflow_exact a b ha hb

theorem source_mul_guard_correct (a b : Int) :
    ¬ sourceMulGuard a b ↔ fits64 (a*b) := by
  have h : sourceMulGuard a b ↔ mulOverflow a b := by
    norm_num [sourceMulGuard, mulOverflow, min64, max64]
  rw [h]
  exact mulOverflow_exact a b

theorem source_small_mul_correct (a b : Int) (h : sourceSmallMul a b) : fits64 (a*b) := by
  apply small_mul_fits
  · norm_num [sourceSmallMul] at h
    omega
  · norm_num [sourceSmallMul] at h
    omega

theorem source_div_guard_correct (a b : Int) : sourceDivGuard a b ↔ divInvalid a b := by
  norm_num [sourceDivGuard, divInvalid, min64]

theorem source_rem_guard_correct (a b : Int) : sourceRemGuard a b ↔ divInvalid a b := by
  norm_num [sourceRemGuard, divInvalid, min64]

end Refpoly.CudaIP
''']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true')
    args = parser.parse_args()
    value = generated()
    if args.write:
        OUTPUT.write_text(value)
    elif not OUTPUT.is_file() or OUTPUT.read_text() != value:
        raise SystemExit('IP arithmetic source changed; regenerate and recheck Lean proofs')
    else:
        print('IP arithmetic source matches the generated Lean guards and checked return bodies')


if __name__ == '__main__':
    main()
