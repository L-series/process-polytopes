#!/usr/bin/env python3
"""Translate the actual arithmetic expression in device_eval_eq into Lean.

The deliberately small frontend accepts only its side-effect-free return
expression. Unrecognized syntax is an error, never an assumed contract.
The frontend itself is part of the source-linking trusted boundary.
"""
import argparse
import ast
import hashlib
import re
from pathlib import Path
from test_gpu_ip_source import block

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/gpu/ip_check.cuh'
OUTPUT = ROOT / 'proofs/Refpoly/CudaIPSource.lean'


def translate(node):
    if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Mult)):
        op = 'add' if isinstance(node.op, ast.Add) else 'mul'
        return f'(.{op} {translate(node.left)} {translate(node.right)})'
    if isinstance(node, ast.Attribute) and ast.unparse(node) == 'equation.c':
        return '.constant'
    if isinstance(node, ast.Subscript) and isinstance(node.slice, ast.Constant):
        index = node.slice.value
        if type(index) is not int or not 0 <= index < 5:
            raise ValueError('Out-of-range source index')
        base = ast.unparse(node.value)
        if base in ('equation.a', 'point'):
            kind = 'normal' if base == 'equation.a' else 'point'
            return f'(.{kind} ⟨{index}, by decide⟩)'
    raise ValueError(f'Unsupported source expression: {ast.dump(node)}')


def generated():
    function = block(SOURCE.read_text(), '__device__ long long device_eval_eq(')
    header = re.sub(r'\s+','',function[:function.index('{')])
    if header != '__device__longlongdevice_eval_eq(constDeviceEquation5&equation,constlonglong*point)':
        raise ValueError('Unrecognized typed evaluator signature')
    body = function[function.index('{')+1:function.rindex('}')].strip()
    if not body.startswith('return ') or not body.endswith(';') or body.count(';') != 1:
        raise ValueError('device_eval_eq is not a single return expression')
    expr = translate(ast.parse('(' + body[len('return '):-1].strip() + ')', mode='eval').body)
    normal = block(SOURCE.read_text(), '__device__ int device_equation_has_normal(')
    normal_header = re.sub(r'\s+','',normal[:normal.index('{')])
    if normal_header != '__device__intdevice_equation_has_normal(constDeviceEquation5&equation)':
        raise ValueError('Unrecognized normal-check signature')
    normal_body = normal[normal.index('{')+1:normal.rindex('}')]
    if re.sub(r'\s+','',normal_body) != 'for(inti=0;i<5;++i)if(equation.a[i]!=0)return1;return0;':
        raise ValueError('Unrecognized normal-check loop')
    bounded = block(SOURCE.read_text(), '__device__ int device_eval_bounded(')
    names = (['equation.c'] + [f'equation.a[{i}]' for i in range(5)] + [f'point[{i}]' for i in range(5)])
    limits = [2**61] + [2**44] * 5 + [2**15] * 5
    expected = ('__device__intdevice_eval_bounded(constDeviceEquation5&equation,constlonglong*point){return' +
                '&'.join(f'((unsignedlonglong){n}+{b}ULL<={2 * b}ULL)' for n, b in zip(names, limits)) + ';}')
    if re.sub(r'//[^\n]*|\s+', '', bounded) != expected:
        raise ValueError('device_eval_bounded is not the audited bound conjunction')
    lean_names = ['e.constant'] + [f'e.normal ⟨{i}, by decide⟩' for i in range(5)] + [f'x ⟨{i}, by decide⟩' for i in range(5)]
    # C semantics of (unsigned long long)v + B: (v mod 2^64 + B) mod 2^64.
    bounded_expr = ' ∧ '.join(f'({n} % 2^64 + {b}) % 2^64 ≤ {2 * b}' for n, b in zip(lean_names, limits))
    fits_hyps = ' ∧ '.join(f'fits64 ({n})' for n in lean_names)
    bounded_digest = hashlib.sha256(bounded.encode()).hexdigest()
    hyps = ', '.join(f'h{i}' for i in range(22))
    unsigned_hyps = ', '.join(f'u{i}' for i in range(11))
    fit_names = ', '.join(f'f{i}' for i in range(11))
    decode = '\n'.join(f'  have h{2 * i} : -{b} ≤ {n} := by unfold fits64 at f{i}; omega\n'
                       f'  have h{2 * i + 1} : {n} ≤ {b} := by unfold fits64 at f{i}; omega'
                       for i, (n, b) in enumerate(zip(lean_names, limits)))
    products = '\n'.join(f'  obtain ⟨p{i}l, p{i}u⟩ := term _ _ h{2 + 2 * i} h{3 + 2 * i} h{12 + 2 * i} h{13 + 2 * i}'
                          for i in range(5))
    digest = hashlib.sha256(function.encode()).hexdigest()
    normal_digest = hashlib.sha256(normal.encode()).hexdigest()
    normal_expr = ' || '.join(f'decide (e.normal ⟨{i}, by decide⟩ ≠ 0)' for i in range(5))
    return f'''-- Generated by scripts/generate_ip_eval_model.py; do not edit manually.
-- Source-function SHA256: {digest}
import Refpoly.CudaIPExpr

namespace Refpoly.CudaIP

def deviceEvalExpr : EvalExpr := {expr}

/-- Algebraic refinement of the expression extracted from the actual source. -/
theorem device_eval_eq_integer (e : Equation 5) (x : Fin 5 → Int) :
    evalExpr e x deviceEvalExpr = eval e x := by
  simp [deviceEvalExpr, evalExpr, eval, Fin.sum_univ_succ]
  ring

/-- When source signed arithmetic is defined, its result is the exact integer
functional. This theorem does not assume that all pipeline inputs are safe. -/
theorem device_eval_eq_defined (e : Equation 5) (x : Fin 5 → Int) (v : Int) :
    checkedEval e x deviceEvalExpr = some v ↔
      expressionDefined e x deviceEvalExpr ∧ v = eval e x := by
  rw [checkedEval_exact, device_eval_eq_integer]

-- Bound-check source-function SHA256: {bounded_digest}
def sourceEvalBounded (e : Equation 5) (x : Fin 5 → Int) : Prop := {bounded_expr}

/-- Inside the source bound check every product of the raw evaluator fits in
2^59 and every partial sum in 2^61 + 5 * 2^59 < 2^63, so the unchecked fast
path computes exactly what the checked path would. The values are C signed
64-bit operands, hence the `fits64` premises. -/
theorem source_eval_bounded_defined (e : Equation 5) (x : Fin 5 → Int)
    (h : sourceEvalBounded e x) (hfit : {fits_hyps}) :
    expressionDefined e x deviceEvalExpr := by
  obtain ⟨{unsigned_hyps}⟩ := h
  obtain ⟨{fit_names}⟩ := hfit
{decode}
  have term : ∀ a y : Int, -{2**44} ≤ a → a ≤ {2**44} → -{2**15} ≤ y → y ≤ {2**15} →
      -(2^59) ≤ a * y ∧ a * y ≤ 2^59 := by
    intro a y h1 h2 h3 h4
    have hb : |a * y| ≤ 2^59 := by
      rw [abs_mul]
      calc |a| * |y| ≤ {2**44} * {2**15} :=
            mul_le_mul (abs_le.mpr ⟨h1, h2⟩) (abs_le.mpr ⟨h3, h4⟩) (abs_nonneg _) (by norm_num)
        _ = 2^59 := by norm_num
    exact abs_le.mp hb
{products}
  simp only [expressionDefined, deviceEvalExpr, evalExpr, fits64]
  constructorm* _ ∧ _, True
  all_goals first | trivial | linarith

theorem source_eval_bounded_exact (e : Equation 5) (x : Fin 5 → Int)
    (h : sourceEvalBounded e x) (hfit : {fits_hyps}) :
    checkedEval e x deviceEvalExpr = some (eval e x) :=
  (device_eval_eq_defined e x _).mpr ⟨source_eval_bounded_defined e x h hfit, rfl⟩

-- Normal-check source-function SHA256: {normal_digest}
def sourceHasNormal (e : Equation 5) : Bool := {normal_expr}

theorem source_has_normal_correct (e : Equation 5) :
    sourceHasNormal e = true ↔ e.normal ≠ 0 := by
  have h : (e.normal ≠ 0) ↔ ∃ i : Fin 5, e.normal i ≠ 0 := by
    simp [funext_iff]
  rw [h]
  simp [sourceHasNormal, Fin.exists_fin_succ, or_assoc]

end Refpoly.CudaIP
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    result = generated()
    if args.write:
        OUTPUT.write_text(result)
    elif not OUTPUT.is_file() or OUTPUT.read_text() != result:
        raise SystemExit('Source evaluator changed; regenerate and recheck its Lean proofs')
    else:
        print('Source evaluator matches the generated Lean expression')


if __name__ == '__main__':
    main()
