#!/usr/bin/env python3
"""Check the independent reason-4 gate and source-link its finite scan to Lean.

This is a deliberately restricted, trusted source frontend. It accepts exactly
one checked evaluation per point, a sticky arithmetic-failure flag, and the
nonzero-normal/constant guards. Other syntax requires review, not an axiom.
"""
import argparse
import hashlib
from pathlib import Path
import re
from test_gpu_ip_source import block

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'proofs/Refpoly/CudaIPCertificate.lean'


def generated():
    source = (ROOT / 'src/gpu/ip_check.cuh').read_text()
    function = block(source, '__device__ int device_ip_supporting_certificate(')
    body = re.sub(r'\s+', '', function[function.index('{')+1:function.rindex('}')])
    expected = ('if(point_count<1||equation.c>0||!device_equation_has_normal(equation))return0;'
                'for(inti=0;i<point_count;++i)'
                'if(device_ip_eval_eq(equation,points+i*5,arithmetic_failed)<0)return0;'
                'return!*arithmetic_failed;')
    if body != expected:
        raise ValueError('Unrecognized supporting-certificate gate; review and reprove')
    digest = hashlib.sha256(function.encode()).hexdigest()
    return '''-- Generated by scripts/generate_ip_certificate_model.py; do not edit.
-- Source-function SHA256: ''' + digest + '''
import Refpoly.CudaIPSource

namespace Refpoly.CudaIP

/-- Successful finite scan with checked evaluation. Arithmetic failure is
sticky: one undefined evaluation makes the whole gate inconclusive. -/
def checkedNonnegative (e : Equation 5) : List (Fin 5 → Int) → Bool
  | [] => true
  | x :: xs => match checkedEval e x deviceEvalExpr with
    | none => false
    | some value => decide (0 ≤ value) && checkedNonnegative e xs

def sourceSupportingCertificate (e : Equation 5) (xs : List (Fin 5 → Int)) : Bool :=
  !xs.isEmpty && decide (e.constant ≤ 0) && sourceHasNormal e && checkedNonnegative e xs

/-- No unchecked arithmetic conclusion is hidden in a successful gate. -/
theorem checkedNonnegative_exact (e : Equation 5) (xs : List (Fin 5 → Int)) :
    checkedNonnegative e xs = true ↔
      ∀ x ∈ xs, expressionDefined e x deviceEvalExpr ∧ 0 ≤ eval e x := by
  induction xs with
  | nil => simp [checkedNonnegative]
  | cons x xs ih =>
    cases he : checkedEval e x deviceEvalExpr with
    | none =>
      have hn : ¬expressionDefined e x deviceEvalExpr := by
        intro hd
        have hs := (device_eval_eq_defined e x (eval e x)).mpr ⟨hd, rfl⟩
        simp [he] at hs
      simp [checkedNonnegative, he, hn]
    | some value =>
      obtain ⟨hd, hv⟩ := (device_eval_eq_defined e x value).mp he
      simp [checkedNonnegative, he, ih, hv, hd]

/-- The independent gate is sufficient for rejection, regardless of how a
hull routine proposed the equation. Full point-set coverage is a separate
pipeline obligation; this theorem uses exactly the supplied point family. -/
theorem sourceSupportingCertificate_sound (e : Equation 5) (xs : List (Fin 5 → Int))
    (h : sourceSupportingCertificate e xs = true) :
    ¬ IsIP (KS.PolyCode.hull ⟨xs⟩) := by
  have facts : (!xs.isEmpty = true ∧ e.constant ≤ 0) ∧
      e.normal ≠ 0 ∧ checkedNonnegative e xs = true := by
    simpa [sourceSupportingCertificate, Bool.and_eq_true, source_has_normal_correct,
      and_assoc] using h
  apply integer_supporting_rejection xs e facts.2.1 (by omega)
  intro x hx
  exact ((checkedNonnegative_exact e xs).mp facts.2.2 x hx).2

end Refpoly.CudaIP
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    result = generated()
    if args.write:
        OUTPUT.write_text(result)
    elif not OUTPUT.is_file() or OUTPUT.read_text() != result:
        raise SystemExit('Certificate gate changed; regenerate and recheck its proof')
    else:
        print('Source supporting-certificate gate matches its Lean model')


if __name__ == '__main__':
    main()
